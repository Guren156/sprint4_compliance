-- Criação das tabelas
CREATE TABLE VETERINARIOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    CRMV VARCHAR2(20) UNIQUE NOT NULL,
    TELEFONE VARCHAR2(20),
    ESPECIALIDADE VARCHAR2(50),
    DATA_CADASTRO DATE DEFAULT SYSDATE,
    ATIVO NUMBER(1) DEFAULT 1,
    ROLE VARCHAR2(20) DEFAULT 'VETERINARIO'
);

CREATE TABLE ANIMAIS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    ESPECIE VARCHAR2(50) NOT NULL,
    RACA VARCHAR2(50),
    IDADE NUMBER,
    PESO NUMBER(10,2),
    SEXO CHAR(1),
    TUTOR_NOME VARCHAR2(100) NOT NULL,
    TUTOR_TELEFONE VARCHAR2(20) NOT NULL,
    TUTOR_EMAIL VARCHAR2(100),
    DATA_CADASTRO DATE DEFAULT SYSDATE,
    OBSERVACOES VARCHAR2(500),
    ATIVO NUMBER(1) DEFAULT 1
);

CREATE TABLE CONSULTAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ANIMAL_ID NUMBER NOT NULL,
    VETERINARIO_ID NUMBER NOT NULL,
    DATA_HORA TIMESTAMP NOT NULL,
    MOTIVO VARCHAR2(200),
    DIAGNOSTICO VARCHAR2(500),
    PRESCRICAO VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'AGENDADA',
    LEMBRETE_ENVIADO NUMBER(1) DEFAULT 0,
    FOREIGN KEY (ANIMAL_ID) REFERENCES ANIMAIS(ID),
    FOREIGN KEY (VETERINARIO_ID) REFERENCES VETERINARIOS(ID)
);

CREATE TABLE LEMBRETES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONSULTA_ID NUMBER NOT NULL,
    TUTOR_EMAIL VARCHAR2(100),
    TUTOR_TELEFONE VARCHAR2(20),
    MENSAGEM VARCHAR2(500),
    DATA_ENVIO DATE DEFAULT SYSDATE,
    ENVIADO NUMBER(1) DEFAULT 0,
    TIPO VARCHAR2(10),
    FOREIGN KEY (CONSULTA_ID) REFERENCES CONSULTAS(ID)
);